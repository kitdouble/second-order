// Generates a standalone R script that reproduces the platform's participant
// measures, exclusions and primary Bayes factor from the exported CSV.
// Base R plus BayesFactor only. The R result is the result of record.
import { getBlock } from "./blocks/index.js";
import { listConditions, resolveCond } from "./conditions.js";
import { stepId } from "./compile.js";
import { parseExpr } from "./expr.js";
import { primaryGroups } from "./simulate.js";

const rStr = (s) => JSON.stringify(String(s));

function exprToR(src) {
  const ast = parseExpr(src);
  const go = (n) => {
    switch (n.k) {
      case "lit":
        return n.v === true ? "TRUE" : n.v === false ? "FALSE" : n.v === null ? "NA" : String(n.v);
      case "id":
        return "`" + n.v + "`";
      case "not":
        return `!(${go(n.a)})`;
      case "and":
        return `(${go(n.a)} & ${go(n.b)})`;
      case "or":
        return `(${go(n.a)} | ${go(n.b)})`;
      case "cmp":
        return `(${go(n.a)} ${n.op} ${go(n.b)})`;
    }
  };
  return go(ast);
}

// Row filter over a step's columns, as an R index on data frame `s`.
function filterToR(src) {
  const ast = parseExpr(src);
  const go = (n) => {
    switch (n.k) {
      case "lit":
        return n.v === true ? "TRUE" : n.v === false ? "FALSE" : n.v === null ? "NA" : typeof n.v === "string" ? JSON.stringify(n.v) : String(n.v);
      case "id":
        return `s[[${JSON.stringify(n.v)}]]`;
      case "not":
        return `!(${go(n.a)})`;
      case "and":
        return `(${go(n.a)} & ${go(n.b)})`;
      case "or":
        return `(${go(n.a)} | ${go(n.b)})`;
      case "cmp":
        return `(${go(n.a)} ${n.op} ${go(n.b)})`;
    }
  };
  return go(ast);
}

function whereToR(where, v) {
  if (!where) return "TRUE";
  const m = /^\s*(==|!=|<=|>=|<|>)\s*(-?\d+(?:\.\d+)?)\s*$/.exec(where);
  return `(${v} ${m[1]} ${m[2]})`;
}

export function generateRScript(spec, { hash = "draft", generatedAt = new Date().toISOString() } = {}) {
  const conds = listConditions(spec);
  const factors = Object.keys(spec.design.between);
  const L = [];
  L.push(`# ${spec.study.title}`);
  L.push(`# Analysis script generated by Second Order from spec ${hash} (${generatedAt}).`);
  L.push(`# Reproduces participant measures, exclusions and the primary Bayes factor`);
  L.push(`# from trials.csv. Needs base R and the BayesFactor package.`);
  L.push(`#`);
  L.push(`# Usage: put trials.csv (and optionally participants.csv from the platform)`);
  L.push(`# next to this script, then run it. If participants.csv is present, the`);
  L.push(`# script checks that its numbers match the platform's.`);
  L.push(``);
  L.push(`suppressPackageStartupMessages(library(BayesFactor))`);
  L.push(``);
  L.push(`trials <- read.csv("trials.csv", stringsAsFactors = FALSE)`);
  L.push(`as_logical <- function(x) if (is.logical(x)) x else toupper(as.character(x)) %in% c("TRUE", "T", "1")`);
  L.push(``);
  L.push(META_D_R);
  L.push(``);

  // Per-condition parameters the measures need.
  const scaleLines = [];
  const likertLines = [];
  for (const item of spec.sequence) {
    const block = getBlock(spec.blocks[item.use]);
    const id = stepId(item);
    for (const c of conds) {
      const p = block.params.parse(resolveCond(item.params ?? {}, c.levels));
      if (block.sdt && p.confidence) scaleLines.push(`  ${rStr(`${id}|${c.key}`)} = c(${p.confidence.scale[0]}, ${p.confidence.scale[1]})`);
      if (block.ref.startsWith("likert")) likertLines.push(`  ${rStr(`${id}|${c.key}`)} = c(${p.scale.min}, ${p.scale.max})`);
    }
  }
  L.push(`# Confidence scale for each step and condition.`);
  L.push(`conf_scale <- list(\n${scaleLines.join(",\n")}\n)`);
  if (likertLines.length) L.push(`likert_scale <- list(\n${likertLines.join(",\n")}\n)`);
  L.push(``);

  L.push(`score_session <- function(d) {`);
  L.push(`  cond <- d$condition[1]`);
  L.push(`  step <- function(id) d[d$step == id, , drop = FALSE]`);
  L.push(`  out <- list(session_id = d$session_id[1], condition = cond)`);
  for (const f of factors) L.push(`  out[[${rStr(f)}]] <- d[[${rStr(f)}]][1]`);

  // Summaries.
  for (const item of spec.sequence) {
    const block = getBlock(spec.blocks[item.use]);
    const id = stepId(item);
    if (block.ref.startsWith("attention")) L.push(`  s <- step(${rStr(id)}); out[[${rStr(`${id}.passed`)}]] <- if (nrow(s)) as_logical(s$passed[1]) else NA`);
    if (block.ref.startsWith("consent")) L.push(`  s <- step(${rStr(id)}); out[[${rStr(`${id}.consented`)}]] <- if (nrow(s)) as_logical(s$consented[1]) else NA`);
    if (block.ref.startsWith("likert")) {
      L.push(`  s <- step(${rStr(id)}); sc <- likert_scale[[paste0(${rStr(id)}, "|", cond)]]`);
      L.push(`  out[[${rStr(`${id}.score`)}]] <- if (nrow(s)) mean(ifelse(as_logical(s$reverse), sc[1] + sc[2] - s$response, s$response)) else NA`);
    }
  }

  // Measures.
  const filterLine = (m) => (m.filter ? [`  s <- s[which(${filterToR(m.filter)}), , drop = FALSE]  # ${m.filter}`] : []);
  for (const [name, m] of Object.entries(spec.measures)) {
    const key = rStr(name);
    if (m.fn === "diff") continue;
    if (["d_prime", "meta_d", "mratio"].includes(m.fn)) {
      L.push(`  s <- step(${rStr(m.from)})`);
      L.push(...filterLine(m));
      if (m.fn === "d_prime") {
        L.push(`  out[[${key}]] <- if (nrow(s)) type_one(s)$d_prime else NA`);
      } else {
        L.push(`  fit <- if (nrow(s)) meta_d_from_trials(s, conf_scale[[paste0(${rStr(m.from)}, "|", cond)]]) else NULL`);
        L.push(`  out[[${key}]] <- if (is.null(fit) || is.null(fit$meta_d)) NA else ${m.fn === "meta_d" ? "fit$meta_d" : "fit$mratio"}`);
      }
      continue;
    }
    const [id, col] = m.of.split(".");
    L.push(`  s <- step(${rStr(id)})`);
    L.push(...filterLine(m));
    if (m.fn === "count") {
      L.push(`  out[[${key}]] <- ${col ? `sum(!is.na(s[[${rStr(col)}]]))` : "nrow(s)"}`);
    } else if (m.fn === "first") {
      L.push(`  out[[${key}]] <- if (nrow(s)) s[[${rStr(col)}]][1] else NA`);
    } else {
      L.push(`  v <- s[[${rStr(col)}]]; if (is.character(v) || is.logical(v)) v <- as.numeric(as_logical(v)); v <- v[!is.na(v)]`);
      if (m.fn === "prop") L.push(`  out[[${key}]] <- if (length(v)) mean(${whereToR(m.where, "v")}) else NA`);
      else {
        L.push(`  v <- v[${whereToR(m.where, "v")}]`);
        const f = m.fn === "mean" ? "mean(v)" : m.fn === "sd" ? "if (length(v) > 1) sd(v) else NA" : "median(v)";
        L.push(`  out[[${key}]] <- if (length(v)) ${f} else NA`);
      }
    }
  }
  for (const [name, m] of Object.entries(spec.measures)) {
    if (m.fn !== "diff") continue;
    L.push(`  out[[${rStr(name)}]] <- as.numeric(out[[${rStr(m.a)}]]) - as.numeric(out[[${rStr(m.b)}]])  # ${m.a} minus ${m.b}`);
  }
  L.push(`  as.data.frame(out, check.names = FALSE, stringsAsFactors = FALSE)`);
  L.push(`}`);
  L.push(``);
  L.push(`participants <- do.call(rbind, lapply(split(trials, trials$session_id), score_session))`);
  L.push(``);

  // Exclusions.
  L.push(`# Exclusions: flagged, never deleted. A missing value counts as excluded.`);
  const exIds = [];
  for (const ex of spec.exclusions) {
    exIds.push(ex.id);
    L.push(`participants[[${rStr(`excl_${ex.id}`)}]] <- with(participants, ${exprToR(ex.when)})`);
    L.push(`participants[[${rStr(`excl_${ex.id}`)}]][is.na(participants[[${rStr(`excl_${ex.id}`)}]])] <- TRUE`);
  }
  L.push(
    exIds.length
      ? `participants$excluded <- Reduce(\`|\`, participants[${JSON.stringify(exIds.map((i) => `excl_${i}`)).replace(/^\[/, "c(").replace(/\]$/, ")")}])`
      : `participants$excluded <- FALSE`,
  );
  L.push(`included <- participants[!participants$excluded, ]`);
  L.push(`cat("Participants:", nrow(participants), " included:", nrow(included), "\\n")`);
  L.push(``);

  const g = primaryGroups(spec);
  if (g) {
    const pr = spec.analysis.primary;
    L.push(`# Primary analysis: ${pr.hypothesis}`);
    L.push(`x <- included[[${rStr(pr.dv)}]][included[[${rStr(g.factor)}]] == ${rStr(g.x)}]`);
    L.push(`y <- included[[${rStr(pr.dv)}]][included[[${rStr(g.factor)}]] == ${rStr(g.y)}]`);
    L.push(`x <- x[is.finite(x)]; y <- y[is.finite(y)]`);
    L.push(
      g.directional
        ? `bf <- ttestBF(x = x, y = y, rscale = ${pr.prior?.cauchy_r ?? 0.707}, nullInterval = c(0, Inf))[1]  # ${g.x} > ${g.y}`
        : `bf <- ttestBF(x = x, y = y, rscale = ${pr.prior?.cauchy_r ?? 0.707})`,
    );
    L.push(`bf10 <- extractBF(bf)$bf[1]`);
    L.push(`cat(sprintf("%s: n = %d vs %d, means %.3f vs %.3f, BF10 = %.3f\\n", ${rStr(pr.dv)}, length(x), length(y), mean(x), mean(y), bf10))`);
    L.push(``);
  }

  L.push(`# Check against the platform's own numbers, if exported.`);
  L.push(`if (file.exists("participants.csv")) {`);
  L.push(`  plat <- read.csv("participants.csv", stringsAsFactors = FALSE, check.names = FALSE)`);
  L.push(`  m <- merge(participants, plat, by = "session_id", suffixes = c("", ".platform"))`);
  L.push(`  for (v in ${JSON.stringify(Object.keys(spec.measures)).replace(/^\[/, "c(").replace(/\]$/, ")")}) {`);
  L.push(`    d <- max(abs(as.numeric(m[[v]]) - as.numeric(m[[paste0(v, ".platform")]])), na.rm = TRUE)`);
  L.push(`    cat(sprintf("  %-12s max difference vs platform: %.2e\\n", v, d))`);
  L.push(`  }`);
  L.push(`  cat("  exclusion agreement:", mean(as_logical(m$excluded) == as_logical(m$excluded.platform)), "\\n")`);
  L.push(`}`);
  return L.join("\n") + "\n";
}

// R port of metad.js. Same padding, parameterisation and likelihood.
const META_D_R = String.raw`# ---- SDT and meta-d' (Maniscalco & Lau, 2012) --------------------------------
type_one <- function(s) {
  s2 <- sum(s$side == "right"); s1 <- sum(s$side == "left")
  h <- sum(s$side == "right" & s$response == "right")
  fa <- sum(s$side == "left" & s$response == "right")
  HR <- (h + 0.5) / (s2 + 1); FAR <- (fa + 0.5) / (s1 + 1)
  list(d_prime = qnorm(HR) - qnorm(FAR), c = -0.5 * (qnorm(HR) + qnorm(FAR)))
}

rating_counts <- function(s, scale) {
  K <- scale[2] - scale[1] + 1
  nR_S1 <- numeric(2 * K); nR_S2 <- numeric(2 * K)
  s <- s[!is.na(s$confidence), ]
  k <- round(s$confidence - scale[1] + 1)
  idx <- ifelse(s$response == "left", K - k, K - 1 + k) + 1
  for (i in seq_along(idx)) {
    if (s$side[i] == "left") nR_S1[idx[i]] <- nR_S1[idx[i]] + 1 else nR_S2[idx[i]] <- nR_S2[idx[i]] + 1
  }
  list(nR_S1 = nR_S1, nR_S2 = nR_S2)
}

fit_meta_d <- function(nR_S1, nR_S2) {
  K <- length(nR_S1) / 2
  a <- nR_S1 + 1 / (2 * K); b <- nR_S2 + 1 / (2 * K)
  HR <- sum(b[(K + 1):(2 * K)]) / sum(b); FAR <- sum(a[(K + 1):(2 * K)]) / sum(a)
  d1 <- qnorm(HR) - qnorm(FAR); c1 <- -0.5 * (qnorm(HR) + qnorm(FAR))
  if (!(d1 > 0.05)) return(list(d_prime = d1, meta_d = NULL, mratio = NULL))
  cp <- c1 / d1
  nll <- function(x) {
    md <- x[1]; mc <- cp * md
    if (!is.finite(md) || abs(md) > 20) return(1e12)
    tS1 <- mc - cumsum(exp(x[2:K])); tS2 <- mc + cumsum(exp(x[(K + 1):(2 * K - 1)]))
    ll <- 0
    for (st in 1:2) {
      mu <- if (st == 1) -md / 2 else md / 2
      cnt <- if (st == 1) a else b
      p1 <- pnorm(mc - mu); p2 <- 1 - p1
      if (p1 <= 1e-12 || p2 <= 1e-12) return(1e12)
      for (k in 1:K) {
        up <- if (k == 1) mc else tS1[k - 1]
        lo <- if (k == K) -Inf else tS1[k]
        p <- (pnorm(up - mu) - pnorm(lo - mu)) / p1
        ll <- ll + cnt[K - k + 1] * log(max(p, 1e-12))
        lo <- if (k == 1) mc else tS2[k - 1]
        up <- if (k == K) Inf else tS2[k]
        p <- (pnorm(up - mu) - pnorm(lo - mu)) / p2
        ll <- ll + cnt[K + k] * log(max(p, 1e-12))
      }
    }
    -ll
  }
  x0 <- c(d1, rep(log(0.5), 2 * (K - 1)))
  f <- optim(x0, nll, method = "Nelder-Mead", control = list(maxit = 20000, reltol = 1e-12))
  f <- optim(f$par, nll, method = "BFGS", control = list(maxit = 2000, reltol = 1e-14))
  list(d_prime = d1, meta_d = f$par[1], mratio = f$par[1] / d1, logL = -f$value)
}

meta_d_from_trials <- function(s, scale) {
  r <- rating_counts(s, scale)
  if (sum(r$nR_S1) == 0 || sum(r$nR_S2) == 0) return(NULL)
  fit_meta_d(r$nR_S1, r$nR_S2)
}`;
