// Regenerates packages/core/src/examples.js from packages/core/examples/*.yaml,
// so the web app and MCP can serve them without reading files at runtime.
// Run after editing an example: node scripts/embed-examples.mjs
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../packages/core/examples/", import.meta.url);
const files = { dots: "dots-feedback-mratio.yaml", flanker: "flanker-feedback.yaml", custom: "custom-gonogo.yaml" };
const lines = ["// Generated by scripts/embed-examples.mjs from packages/core/examples/. Don't edit by hand.", ""];
for (const [name, file] of Object.entries(files)) {
  lines.push(`export const EXAMPLE_${name.toUpperCase()}_YAML = ${JSON.stringify(readFileSync(new URL(file, dir), "utf8"))};`, "");
}
lines.push(
  "/** Worked examples by name: what each shows. */",
  "export const EXAMPLES = {",
  '  dots: { yaml: EXAMPLE_DOTS_YAML, shows: "Dot discrimination with confidence, meta-d\'/M-ratio, staircase, feedback manipulation, stopping rule." },',
  '  flanker: { yaml: EXAMPLE_FLANKER_YAML, shows: "A choice-RT task (arrow flanker) built from choice-rt@1: stimuli list, filtered RT measures and a difference score." },',
  '  custom: { yaml: EXAMPLE_CUSTOM_YAML, shows: "A go/no-go task written as custom jsPsych code (custom-jspsych@1): the api contract, declared columns, expected rows." },',
  "};",
  "",
);
writeFileSync(new URL("../packages/core/src/examples.js", import.meta.url), lines.join("\n"));
console.log("examples.js written");
